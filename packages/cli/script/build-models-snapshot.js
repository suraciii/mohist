import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const srcSnapshotJs = path.join(rootDir, 'src', 'config', 'models-snapshot.js');
const srcSnapshotDts = path.join(rootDir, 'src', 'config', 'models-snapshot.d.ts');
const srcSnapshotTs = path.join(rootDir, 'src', 'config', 'models-snapshot.ts');

const SOURCE_URL = 'https://models.dev';

async function fetchModelsData() {
  try {
    const url = process.env.MODELS_DEV_API_JSON
      ? `file://${path.resolve(process.env.MODELS_DEV_API_JSON)}`
      : `${SOURCE_URL}/api.json`;
    const response = await fetch(url, {
      signal: AbortSignal.timeout(30000),
    });
    if (!response.ok) {
      console.error(`Failed to fetch models data: ${response.status} ${response.statusText}`);
      return null;
    }
    return response.text();
  } catch (err) {
    console.error(`Failed to fetch models data: ${err}`);
    return null;
  }
}

function cleanupOldTsFile() {
  if (fs.existsSync(srcSnapshotTs)) {
    fs.unlinkSync(srcSnapshotTs);
  }
}

function writeSnapshotJs(data) {
  const jsContent = `// @ts-nocheck
// Auto-generated by build script - do not edit
export const snapshot = ${data}
`;
  fs.writeFileSync(srcSnapshotJs, jsContent, { encoding: 'utf-8' });
  console.log(`Generated ${srcSnapshotJs}`);
}

function writeSnapshotDts() {
  const dtsContent = `// Auto-generated by build script - do not edit
export declare const snapshot: Record<string, unknown>
`;
  fs.writeFileSync(srcSnapshotDts, dtsContent, { encoding: 'utf-8' });
  console.log(`Generated ${srcSnapshotDts}`);
}

function snapshotExists() {
  return fs.existsSync(srcSnapshotJs);
}

async function main() {
  cleanupOldTsFile();

  const data = await fetchModelsData();

  if (data) {
    try {
      JSON.parse(data);
      writeSnapshotJs(data);
      writeSnapshotDts();
      return;
    } catch {
      console.error('Invalid JSON data from models.dev');
    }
  }

  if (snapshotExists()) {
    console.log('Using existing snapshot (network unavailable)');
    return;
  }

  console.error('No existing snapshot found and network unavailable. Provide MODELS_DEV_API_JSON env var or run build with network access.');
  process.exit(1);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});